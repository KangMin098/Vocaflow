// scripts/csat/clean-passage.mjs
//
// **지문에서 문항 부속물을 걷어낸다.** (§10.29)
//
// 왜 필요했나 — 2026-08-26, D1(지문 선정)에 규칙을 세우려고 봉투(전 회차 min/max)를 재다가
// 양 극단이 **추출 결함**임을 알았다:
//   · 2022/37 ORDER 2257자 — 시험지 **두 단이 섞여** 들어갔다
//     ("In spite of the likeness between the fictional and real **As long as the irrealism of the silent**...")
//   · 2018/40 SUMMARY — 발문 조각이 지문 앞에 붙었다 ("(B)에 들어갈 말로 가장 적절한 것은?")
//   · 2019/35 IRRELEVANT 178자 — **잘렸다**
// 전수로 재니 논설문 코어 237편 중 **200편(84.4%)** 에 부속물이 섞여 있었다.
// 대부분은 각주 뜻풀이(`* deviate: 벗어나다`)와 발문 조각이다.
//
// **그 위에 §10 의 모든 대역이 세워져 있었다.** 그래서 얼마나 움직이는지부터 쟀다:
//
// | 축 | 원본 중앙 | 청소 중앙 | 이동 |
// |---|---|---|---|
// | 글자수 | 1017 | 977 | **−40** |
// | 낱말수 | 161 | 158 | −3 |
// | **문장당 낱말** | 19.75 | **21.43** | **+1.68 (+8.5%)** |
// | 낱말 길이 | 4.99 | 4.98 | −0.01 |
// | 어휘 다양도 | 0.638 | 0.642 | +0.004 |
//
// **낱말 길이와 어휘 다양도는 사실상 안 움직인다** — §10.14 의 병목 진단(낱말 길이)은 그대로다.
// **문장당 낱말은 움직인다** — 부속물이 문장으로 세어져 분모를 부풀리고 있었다.
//
// ⚠️ **탐욕 매칭 함정.** 처음 쓴 각주 정규식은 `[^*]*` 로 다음 `*` 까지 먹었는데,
//    각주가 지문 **중간**에 끼는 경우(2025/31 의 `* crude: 투박한`)에 **본문 나머지를 통째로** 삼켰다
//    (1045자 → 399자, −62%). 각주 값은 **한글 덩어리에서 끝난다**로 고쳤다.
//
// ⚠️ 이 청소기는 **섞인 두 단을 복원하지 못한다.** 부속물을 걷어낼 뿐이다.
//    두 단이 섞인 지문(2022/37·38 등)은 여전히 못 쓴다 — `looksInterleaved` 로 **표시만** 한다.

/** 각주 뜻풀이: `* deviate: 벗어나다` — 값이 한글 덩어리에서 끝난다 (탐욕 금지) */
const GLOSS = /\*{1,3}\s*[A-Za-z][A-Za-z\s'-]{0,30}\s*[:：]\s*[가-힣][가-힣\s,·()]*/g
/** 발문 조각 — 한국어 지시문이 지문에 섞인 경우 그 문장만 */
const STEM = /[^.!?]*?(다음 글의|밑줄 친|가장 적절한|들어갈 말로|글의 순서로|주어진 글|어법상|위 글의|윗글의|것은\?)[^.!?]*/g
const KOREAN = /[가-힣][가-힣\s,·()]*/g

/** 지문에서 문항 부속물을 걷어낸다. 영어 본문은 건드리지 않는다. */
export function cleanPassage(p) {
  if (!p) return p
  let t = p
  t = t.replace(GLOSS, ' ')
  t = t.replace(/\[\s*3\s*점\s*\]/g, ' ')
  t = t.replace(STEM, ' ')
  t = t.replace(KOREAN, ' ')          // 남은 한글 덩어리 (각주 표시 없이 붙은 것)
  t = t.replace(/\(\s*[AB]\s*\)/g, ' ')
  return t.replace(/\s{2,}/g, ' ').trim()
}

/**
 * 두 단이 섞였는지 **의심** 신호. 복원은 못 하고 표시만 한다.
 * 신호: 유형 대역의 두 배가 넘는 길이 · 대문자로 시작하지 않는 절이 문장 중간에 끼어듦.
 */
export function looksInterleaved(p, typicalChars = 1000) {
  if (!p) return false
  if (p.length > typicalChars * 1.8) return true
  // "...real As long as..." 처럼 소문자 낱말 뒤에 절이 통째로 끼어드는 자리
  return /[a-z]\s+(As long as|In spite of|Retraining|Scientific explanations)\s/.test(p)
}

/** 부속물이 섞여 있었는지 (청소 전후가 다른가) */
export function wasContaminated(p) {
  return cleanPassage(p) !== (p ?? '').replace(/\s{2,}/g, ' ').trim()
}

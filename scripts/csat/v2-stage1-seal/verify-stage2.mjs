// scripts/csat/v2-stage1-seal/verify-stage2.mjs
// Read-only seal verification; never reads author gold keys or unpublished agreement.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const root=path.resolve(process.argv[2] || '');
const expected=process.argv[3];
assert.ok(process.argv[2],'Private Stage 2 directory is required');
assert.match(expected || '',/^[a-f0-9]{64}$/,'Externally anchored Stage 2 seal SHA is required');
const hash=x=>crypto.createHash('sha256').update(x).digest('hex');
const bytes=f=>fs.readFileSync(path.join(root,f));
const read=f=>JSON.parse(bytes(f));
const firstRoot=path.resolve('.local/v2-d2-stage1');
const firstHash='b09a54072f2e45cbcf508f9517eaa9880a48359e2eda865e2bcafab808443f5c';
const firstVerified=JSON.parse(execFileSync(process.execPath,['scripts/csat/v2-stage1-seal/verify.mjs',firstRoot,firstHash],{encoding:'utf8'}));
assert.equal(firstVerified.verified,true);
assert.equal(hash(bytes('SEAL.stage2-r001.json')),expected);
const seal=read('SEAL.stage2-r001.json');
const ledger=read('stage2-submissions.r001.json');
const inputManifest=read('input-manifest.json');
const firstLedger=JSON.parse(fs.readFileSync(path.join(firstRoot,'stage1-submissions.json'),'utf8'));
assert.equal(hash(bytes('stage2-submissions.r001.json')),seal.ledgerSha256);
assert.equal(hash(bytes('input-manifest.json')),seal.inputManifestSha256);
assert.equal(seal.stage1SealSha256,firstHash);
assert.equal(seal.stage1LedgerSha256,firstVerified.ledgerSha256);
assert.equal(inputManifest.ownerLedgerSha256,seal.ownerLedgerSha256);
assert.equal(ledger.sessionId,seal.sessionId);
assert.deepEqual(ledger.results,seal.results);
assert.equal(ledger.riskDefinitions.status,'user-supplied-canonical-definitions-before-seal');
for(const [file,sha] of Object.entries(seal.privateArtifactHashes))assert.equal(hash(bytes(file)),sha,file);
const expectedIds=Object.values(firstLedger.submissions).map(x=>x.itemId).sort();
assert.deepEqual(seal.results.map(x=>x.itemId).sort(),expectedIds);
assert.equal(new Set(seal.results.map(x=>x.itemId)).size,12);
assert.equal(inputManifest.items.length,12);
const statuses=['AGREEMENT_CANDIDATE','DISAGREEMENT','AMBIGUOUS','OPTION_OVERCLAIM','REQUIRES_REDESIGN','INSUFFICIENT_EVIDENCE'];
const actual={reviewed:0,clear:0,ambiguous:0,deferred:0,uniqueClosestCandidate:0,semanticAgreementCandidate:0,targetSpanRedesign:0,redesignRequired:0,primaryStatuses:Object.fromEntries(statuses.map(x=>[x,0])),semanticStatuses:{AGREEMENT_CANDIDATE:0,REQUIRES_REDESIGN:0,AMBIGUOUS:0},polarityShortcutCandidate:0,directAntonymOrDegreeContrast:0,officialBPlusMinimalTextShortcut:0,misfitLexemeOnlyShortcut:0,minimalPhraseRequired:0,f1NotTestedUi:0,f2Risk:0,optionsOnlyUniqueInferenceEstablished:0,v2S5Boundary:0,v2Primary:0,optionOverclaimRisk:0};
for(const entry of seal.results){
 assert.equal(entry.file,`stage2-r001/review-${entry.slug}.stage2.json`);
 const resultBytes=bytes(entry.file),r=JSON.parse(resultBytes);
 assert.equal(hash(resultBytes),entry.sha256,entry.itemId);
 const m=inputManifest.items.find(x=>x.itemId===entry.itemId);
 assert.equal(m.inputFile,`inputs/stage2-${entry.slug}.json`);
 const inputBytes=bytes(m.inputFile),input=JSON.parse(inputBytes);
 assert.equal(hash(inputBytes),m.stage2InputSha256);
 assert.equal(hash(inputBytes),m.ownerLedgerStage2Sha256);
 assert.equal(hash(inputBytes),r.stage2InputSha256);
 assert.equal(hash(inputBytes),entry.stage2InputSha256);
 assert.deepEqual(Object.keys(input).sort(),['itemId','sourceRevision','senseOptions','task'].sort());
 assert.equal(input.task,'stage2');
 const firstEntry=firstLedger.submissions[entry.slug];
 const firstBytes=fs.readFileSync(path.join(firstRoot,firstEntry.file)),first=JSON.parse(firstBytes);
 assert.equal(hash(firstBytes),entry.stage1ReviewSha256);
 assert.equal(hash(firstBytes),r.stage1.reviewSha256);
 assert.equal(first.sourceRevision,r.sourceRevision);
 assert.equal(first.sourceRevision,input.sourceRevision);
 assert.equal(first.contextSenseKo,r.stage1.contextSenseKo);
 assert.equal(first.why,r.stage1.why);
 assert.deepEqual(first.v2S5Boundary,r.v2S5Boundary);
 assert.deepEqual(first.cue.sentences,r.cue.sentences);
 assert.deepEqual(first.cueExpressions,r.cue.keyExpressions);
 assert.equal(r.stage1.retainedUnchanged,true);
 assert.equal(r.revisedAfterStage2,null);
 assert.equal(r.itemId,entry.itemId);
 assert.equal(r.sessionId,seal.sessionId);
 assert.equal(r.reviewedAt,entry.at);
 assert.equal(r.revision,'stage2-r001');
 assert.equal(r.optionReviews.length,input.senseOptions.length);
 r.optionReviews.forEach((o,i)=>{assert.equal(o.text,input.senseOptions[i]);assert.equal(o.number,i+1);assert.equal(o.index,i);assert.ok(o.why.length>20);});
 assert.ok(r.equivalentKoreanAlternatives.length>=2);
 assert.ok(r.cue.sentenceVsExpressionDifference.length>30);
 assert.equal(r.F1.status,'NOT_TESTED_UI');
 assert.equal(r.F2.optionsOnlyFinding,'NOT_ESTABLISHED');
 assert.equal(r.F2.evidenceType,'analytic counterfactual inspection, not observed student behavior');
 assert.equal(r.agreementWithClaudeComputed,false);
 for(const x of Object.values(r.blindAttestation))assert.equal(x,false);
 assert.equal(r.accepted,false);assert.equal(r.releasable,false);assert.equal(r.realLearnableV2Count,0);
 if(r.selectedSenseNumber==='DEFER'){actual.deferred++;assert.equal(r.selectedSenseIndex,null);assert.equal(r.reviewResult,'AMBIGUOUS');}
 else {assert.equal(r.selectedSenseNumber,r.selectedSenseIndex+1);assert.match(r.optionReviews[r.selectedSenseIndex].disposition,/^fits/);actual.uniqueClosestCandidate++;}
 assert.ok(statuses.includes(r.reviewResult));
 actual.reviewed++;actual[r.clarity]++;actual.primaryStatuses[r.reviewResult]++;actual.semanticStatuses[r.semanticResult]++;
 if(r.semanticResult==='AGREEMENT_CANDIDATE')actual.semanticAgreementCandidate++;
 if(r.targetSpanGranularityConcern)actual.targetSpanRedesign++;
 if(r.redesignRequired)actual.redesignRequired++;
 if(r.F2.semanticPolarityShortcut)actual.polarityShortcutCandidate++;
 if(r.F2.directAntonymOrDegreeContrast)actual.directAntonymOrDegreeContrast++;
 if(r.F2.passageHiddenBAndMisfitWordOrPhraseVisibleCandidateSelectable)actual.officialBPlusMinimalTextShortcut++;
 if(r.F2.misfitLexemeOnlySufficient)actual.misfitLexemeOnlyShortcut++;else actual.minimalPhraseRequired++;
 actual.f1NotTestedUi++;if(r.F2.risk)actual.f2Risk++;
 if(r.F2.optionsOnlyWithoutTargetUniqueInferenceEstablished)actual.optionsOnlyUniqueInferenceEstablished++;
 if(r.v2S5Boundary.classification==='boundary')actual.v2S5Boundary++;else actual.v2Primary++;
 if(r.optionOverclaimRisk)actual.optionOverclaimRisk++;
}
assert.deepEqual(actual,ledger.counts);
assert.equal(ledger.agreementComparisonPerformed,false);
assert.equal(ledger.realLearnableV2Count,0);
const receiptPath=path.resolve('docs/research/v2-d2-stage2-20261017/SEAL_RECEIPT.json');
if(fs.existsSync(receiptPath)){
 const receipt=JSON.parse(fs.readFileSync(receiptPath,'utf8'));
 assert.equal(receipt.sealSha256,expected);
 assert.equal(receipt.archiveSha256,hash(bytes('stage2-r001.zip')));
 assert.deepEqual(receipt.counts,actual);
 assert.deepEqual(receipt.results,seal.results);
}
console.log(JSON.stringify({verified:true,stage1StillVerified:true,stage2SealSha256:expected,stage2LedgerSha256:seal.ledgerSha256,counts:actual,claudeComparisonPerformed:false}));

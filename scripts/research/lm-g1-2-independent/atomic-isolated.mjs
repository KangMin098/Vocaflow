// Executes SELECT-captured installed function bodies in local PGlite only. Never connects to dev.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
const root=path.resolve(import.meta.dirname,'../../..')
const req=createRequire(path.join(root,'apps/web/package.json'))
const {PGlite}=req('@electric-sql/pglite')
const snapshot=JSON.parse(fs.readFileSync(path.join(import.meta.dirname,'installed-contract.json'),'utf8'))
const db=new PGlite()
const rows=[]
try {
 for(const table of ['learning_mutations','learning_sessions','learning_task_attempts']) {
  const cols=snapshot.columns.filter(x=>x.table_name===table).map(x=>
    x.column_name+' '+(x.column_name==='id'&&table==='learning_task_attempts'?'bigint generated by default as identity':x.data_type)+
    (x.column_default?' default '+x.column_default:'')+(x.is_nullable==='NO'?' not null':''))
  if(table==='learning_mutations') cols.push('primary key(user_id,client_mutation_id)')
  if(table==='learning_sessions') cols.push('primary key(id)','unique(user_id,client_session_id)')
  if(table==='learning_task_attempts') cols.push('primary key(id)','unique(user_id,client_mutation_id)')
  await db.exec('create table public.'+table+' ('+cols.join(',')+');')
 }
 for(const fn of snapshot.functions) await db.exec(fn.definition)
 const uid='00000000-0000-4000-8000-000000000001'
 const mutation=crypto.randomUUID(), reveal=crypto.randomUUID(), session=crypto.randomUUID()
 const args=[uid,mutation,reveal,session,'theater','practice','fixture#20','independent','2026-10-16T00:00:00Z',false,'claim-support',null,'fixture-hash','{}',true,10,null]
 const sql='select * from public.learning_attempt_submit('+args.map((_,i)=>'$'+(i+1)).join(',')+')'
 const counts=async()=> (await db.query("select (select count(*) from public.learning_sessions)::int sessions,(select count(*) from public.learning_task_attempts)::int attempts,(select count(*) from public.learning_mutations)::int mutations")).rows[0]
 await db.exec("create function public.inject_failure() returns trigger language plpgsql as $$ begin raise exception 'INJECT_AFTER_SESSION_AND_MUTATION'; end $$; create trigger inject before insert on public.learning_task_attempts for each row execute function public.inject_failure();")
 let caught=false
 try {await db.query(sql,args)} catch(e) {caught=String(e).includes('INJECT_AFTER_SESSION_AND_MUTATION')}
 assert.equal(caught,true)
 assert.deepEqual(await counts(),{sessions:0,attempts:0,mutations:0})
 rows.push({id:'A01',status:'PASS',scope:'installed function bodies/local PostgreSQL',afterFailure:await counts()})
 await db.exec('drop trigger inject on public.learning_task_attempts')
 await db.query(sql,args)
 assert.deepEqual(await counts(),{sessions:1,attempts:1,mutations:2})
 rows.push({id:'A02',status:'PASS',afterSuccess:await counts()})
 const retry=await db.query(sql,args)
 assert.equal(retry.rows[0].outcome,'duplicate')
 assert.deepEqual(await counts(),{sessions:1,attempts:1,mutations:2})
 rows.push({id:'A03',status:'PASS',retryOutcome:retry.rows[0].outcome})
 const conflict=[...args]; conflict[14]=false
 const changed=await db.query(sql,conflict)
 assert.equal(changed.rows[0].outcome,'conflict')
 assert.deepEqual(await counts(),{sessions:1,attempts:1,mutations:2})
 rows.push({id:'A04',status:'PASS',changedBody:changed.rows[0].outcome})
} finally {
 await db.close()
 const output={engine:'local PGlite; no production triggers/RLS/concurrency emulation',observedAt:new Date().toISOString(),functions:snapshot.functions.map(x=>({name:x.proname,sha256:crypto.createHash('sha256').update(x.definition).digest('hex')})),rows}
 fs.writeFileSync(path.join(import.meta.dirname,'local/atomic-results.json'),JSON.stringify(output,null,2))
 console.log(JSON.stringify(output))
}

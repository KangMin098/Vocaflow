const FETCH_ONLY = argv.includes('--fetch-only')
/** 장면마다 시드 N개 — 바탕을 뺀 뒤 **투명 비율이 가장 높은 것**을 고른다(물건 뒤에 카드 면이 그려진 결과가 자동 탈락). */

async function api(p, init = {}) {
  const r = await fetch(API + p, { ...init, headers: { ...H, ...(init.headers || {}) } })
  const t = await r.text()
  let j = null
  try { j = JSON.parse(t) } catch { /* 본문이 JSON 이 아님 */ }
  if (!r.ok) throw new Error(`${p} → ${r.status} ${t.slice(0, 300)}`)
  return j
}

// 제목도 커널마다 달라야 한다 — 같은 제목이면 push 가 409 (newTitle 은 slug 에서 만든다)
async function push(jobs) {
  // 같은 커널이 돌고 있으면 새 버전이 그 실행을 덮는다 — 멈춘다(위 함정)
  const cur = await api(`/kernels/status?userName=${USER}&kernelSlug=${SLUG}`).catch(() => null)
  if (/running|queued/.test(String(cur?.status ?? '').toLowerCase())) {
    console.error(`커널 ${SLUG} 이 이미 ${cur.status} — 다른 실행을 덮게 된다. 끝나기를 기다리거나 --slug 로 다른 커널을 쓴다`)
    process.exit(3)
  }
  const body = {
    slug: `${USER}/${SLUG}`, newTitle: SLUG.replace(/-/g, ' '), text: kernelSource(jobs), language: 'python', kernelType: 'script',
    isPrivate: true, enableGpu: true, enableInternet: true, machineShape: 'NvidiaTeslaT4',
    datasetDataSources: [DATASET], competitionDataSources: [], kernelDataSources: [], modelDataSources: [], categoryIds: [],
  }
  const j = await api('/kernels/push', { method: 'POST', body: JSON.stringify(body) })
  if (j?.error) throw new Error(`push: ${j.error}`)
  console.log(`push → ${j?.url ?? '(url 없음)'} · 버전 ${j?.versionNumber ?? '?'}${j?.invalidDatasetSources?.length ? ' · ⚠ 잘못된 Dataset ' + j.invalidDatasetSources : ''}`)
}

async function waitDone() {
  const t0 = Date.now()
  for (;;) {
    const s = await api(`/kernels/status?userName=${USER}&kernelSlug=${SLUG}`).catch((e) => ({ status: 'poll-error ' + e.message }))
    const st = String(s?.status ?? '').toLowerCase()
    process.stdout.write(`\r상태 ${st.padEnd(12)} ${Math.round((Date.now() - t0) / 1000)}s   `)
    if (/complete/.test(st)) { console.log(); return true }
    if (/error|cancel/.test(st)) { console.log(`\n실패 ${JSON.stringify(s).slice(0, 300)}`); return false }
    await new Promise((z) => setTimeout(z, 30_000))
  }
}

async function fetchOutputs() {
  fs.mkdirSync(WORK, { recursive: true })
  let token = null, got = []
  do {
    const q = `/kernels/output?userName=${USER}&kernelSlug=${SLUG}${token ? `&pageToken=${encodeURIComponent(token)}` : ''}`
    const j = await api(q)
    if (j?.logNullable || j?.log) fs.writeFileSync(path.join(WORK, 'kernel.log'), String(j.logNullable ?? j.log))
    for (const f of j?.files ?? []) {
      const name = path.basename(f.fileName ?? f.name ?? '')
      if (!/\.(png|json|log)$/.test(name)) continue
      const buf = Buffer.from(await (await fetch(f.url)).arrayBuffer())
      fs.writeFileSync(path.join(WORK, name), buf)
      got.push(name)
    }
    token = j?.nextPageToken || null
  } while (token)
  console.log(`출력 ${got.length}개 받음 → ${path.relative(ROOT, WORK)}`)
  return got.filter((n) => n.endsWith('.png') && !n.startsWith('_'))
}

async function postprocess(pngs) {
  const byId = Object.fromEntries(SCENES.map((s) => [s.id, s]))
  const b = await chromium.launch()
  const pg = await b.newPage()
  // 바탕을 뺀 결과에서 완전히 투명한 화소의 비율 — 물건 하나가 빈 바탕 위에 있으면 높고, 카드 면이 깔렸으면 낮다
  const clearRatio = (b64) => pg.evaluate(async (src) => {
    const im = new Image(); im.src = src; await im.decode()
    const c = document.createElement('canvas'); c.width = im.width; c.height = im.height
    const g = c.getContext('2d'); g.drawImage(im, 0, 0)
    const d = g.getImageData(0, 0, c.width, c.height).data
    let z = 0; for (let i = 3; i < d.length; i += 16) if (d[i] === 0) z++
    return z / (d.length / 16)
  }, 'data:image/webp;base64,' + b64)
  // Kaggle(Q3 + Lightning) 은 타일 안쪽에 둥근 테두리 액자를 한 겹 더 그린다(앱 아이콘 모양 — 2026-09-22 실측, 두 장 다).
  //   참조 타일은 면이 가장자리까지 꽉 차므로 **사방 10% 를 잘라** 액자를 걷는다. 물건은 가운데 50% 라 잘리지 않는다.
  const cropInset = (src, ratio) => pg.evaluate(async ([data, ratio]) => {
    const im = new Image(); im.src = data; await im.decode()
    const inset = Math.round(im.width * ratio), S = im.width - inset * 2
    const c = document.createElement('canvas'); c.width = 1024; c.height = 1024
    c.getContext('2d').drawImage(im, inset, inset, S, S, 0, 0, 1024, 1024)
    return c.toDataURL('image/png')
  }, [src, ratio])
  const groups = new Map()
  for (const f of pngs) {
    const base = f.replace(/\.png$/, '').replace(/__v\d+$/, '')
    if (!byId[base]) continue
    if (!groups.has(base)) groups.set(base, [])
    groups.get(base).push(f)
  }
  let n = 0
  for (const [id, files] of groups) {
    const s = byId[id]
    let best = null
    for (const f of files) {
      let src = 'data:image/png;base64,' + fs.readFileSync(path.join(WORK, f)).toString('base64')
      // 장면이 `crop` 을 주면 그 비율로(에디션 표지 — 같은 액자가 정사각 표지에도 그려진다, 2026-09-25 28장 중 6장)
      const crop = s.crop ?? (id.startsWith('tile-') ? 0.1 : 0)
      if (crop) src = await cropInset(src, crop)
      const b64 = await pg.evaluate(keyAndEncode, [src, s.key])
      const score = s.key === false ? 0 : await clearRatio(b64)
      if (!best || score > best.score) best = { b64, score, f }
    }
    fs.writeFileSync(path.join(OUT, id + '.webp'), Buffer.from(best.b64, 'base64'))
    n++
    console.log('  ✓ ' + id + (files.length > 1 ? ' ← ' + best.f + ' (투명 ' + Math.round(best.score * 100) + '% · 후보 ' + files.length + ')' : ''))
  }
  await b.close()
  console.log('후처리 ' + n + '장 → ' + path.relative(ROOT, OUT))
}

if (!FETCH_ONLY) {
  const todo = SCENES.filter((s) => (!ONLY || ONLY.includes(s.id)) && (FORCE || !fs.existsSync(path.join(OUT, `${s.id}.webp`))))
  if (!todo.length) { console.log('만들 장면이 없다(전부 있음) — --force 로 다시'); process.exit(0) }
  const jobs = todo.flatMap((s) => {
    const [w, h] = sizeOf(s)
    return Array.from({ length: VARIANTS }, (_, k) => ({ id: VARIANTS > 1 ? `${s.id}__v${k}` : s.id, prompt: `${s.scene} ${s.style}`, neg: NEG, w, h, seed: Math.floor(Math.random() * 2 ** 40) }))
  })
  console.log(`생성 ${jobs.length}: ${jobs.map((j) => j.id).join(' ')}`)
  await push(jobs)
  await new Promise((z) => setTimeout(z, 20_000))
  if (!(await waitDone())) { await fetchOutputs().catch(() => {}); process.exit(1) }
}

// apps/web/tests/e2e-isolated/csat-system-learning.browser.spec.ts
// 실제 정리·도크·CSS와 합성 근거 판을 연결한다. 서버/DB 종단과 실제 학습 효과는 이 검사의 범위가 아니다.
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { expect, test, type Page } from '@playwright/test'

const HARNESS = path.resolve(__dirname, '../../../../.vfc-runs/csat-system-learning-harness.html')
const SHOTS = path.resolve(__dirname, '../../../../.vfc-runs/ui')
const url = (state: string) => `${pathToFileURL(HARNESS).href}#${state}`
test.beforeAll(() => { expect(fs.existsSync(HARNESS)).toBe(true); fs.mkdirSync(SHOTS, { recursive: true }) })
const noWriting = async (page: Page) => { await expect(page.locator('textarea,input[type="text"],[contenteditable="true"]')).toHaveCount(0) }
const stage = (page: Page, n: number) => page.getByTestId(`summary-stage-${n}`).click()
const controls = async (page: Page) => {
  for (const b of await page.getByTestId('learning-summary').locator('button:visible').all()) expect((await b.boundingBox())!.height, await b.innerText()).toBeGreaterThanOrEqual(44)
}
for (const width of [1280, 1440]) {
  test.describe(`PC ${width}×900`, () => {
    test.use({ viewport: { width, height: 900 } })
    test('첫 장면은 질문과 추적 대상 — 설명을 한꺼번에 덤프하지 않는다', async ({ page }) => {
      await page.goto(url('prepared'))
      await expect(page.getByRole('heading', { name: '학습 정리', exact: true })).toBeVisible()
      await expect(page.getByTestId('summary-relation')).toContainText('근거 단위: 문장 · 표 칸')
      await expect(page.getByTestId('summary-evidence-choice')).toHaveCount(2)
      await expect(page.getByTestId('summary-evidence-item')).toHaveCount(0)
      await expect(page.getByTestId('summary-principle')).toHaveCount(0)
      await noWriting(page); await controls(page)
      expect(await page.getByTestId('learning-summary').evaluate(el => getComputedStyle(el).wordBreak)).toBe('keep-all')
      expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
      await page.screenshot({ path: `${SHOTS}/prepared-${width}.png`, fullPage: true })
    })
    test('선택지를 바꾸면 해설 하나와 해당 원문 연결이 함께 바뀐다 — 없는 연결은 추측하지 않는다', async ({ page }) => {
      await page.goto(url('prepared'))
      const choices = page.getByTestId('summary-evidence-choice')
      await choices.first().click()
      await expect(choices.first()).toHaveAttribute('aria-pressed', 'true')
      await expect(page.getByTestId('summary-evidence-item')).toHaveCount(1)
      await expect(page.getByTestId('summary-evidence-item')).toContainText('한정 조건이 빠진 일반화')
      await expect(page.getByTestId('summary-evidence-location')).toContainText('2 · 3번 문장')
      await expect(page.locator('[data-testid="fixture-sentence"][data-selected="true"]')).toHaveCount(2)
      await page.screenshot({ path: `${SHOTS}/trace-${width}.png`, fullPage: true })
      await choices.last().click()
      await expect(page.getByTestId('summary-evidence-item')).toContainText('비용을 말하지 않아요')
      await expect(page.getByTestId('summary-evidence-item')).not.toContainText('일반화')
      await expect(page.getByTestId('summary-evidence-location')).toHaveText('연결 정보 준비 중')
      await expect(page.locator('[data-testid="fixture-sentence"][data-selected="true"]')).toHaveCount(0)
      const acts = await page.evaluate(() => (window as unknown as { __vfActions: unknown[] }).__vfActions)
      expect(acts).toEqual([{ evidence: [2, 3], key: 'summary:analysis:reject:2' }, { evidence: [], key: 'summary:analysis:reject:4' }])
    })
    test('조건을 키보드로 바꾸면 적용/멈춤 경로와 경계가 바뀐다 — 채점·완료 관문 없음', async ({ page }) => {
      await page.goto(url('prepared'))
      const nav = page.getByTestId('summary-stage-1')
      await nav.focus(); await page.keyboard.press('Enter')
      await expect(nav).toHaveAttribute('aria-current', 'step')
      expect(await nav.evaluate(el => getComputedStyle(el).outlineStyle)).not.toBe('none')
      await expect(page.getByTestId('summary-principle')).toContainText('사례가 바뀌어도 남는 공통 주장')
      const applies = page.getByTestId('summary-condition-applies')
      await applies.focus(); await page.keyboard.press('Enter')
      await expect(page.getByTestId('summary-boundary')).toHaveAttribute('data-boundary', 'applies')
      await expect(page.getByTestId('summary-boundary')).toContainText('원리를 적용')
      await page.getByTestId('summary-condition-limit').click()
      await expect(page.getByTestId('summary-boundary')).toHaveAttribute('data-boundary', 'limit')
      await expect(page.getByTestId('summary-boundary')).toContainText('적용을 멈춤')
      await expect(applies).toHaveAttribute('aria-pressed', 'false')
      await controls(page); await noWriting(page)
      await page.screenshot({ path: `${SHOTS}/conditions-${width}.png`, fullPage: true })
      await page.getByTestId('summary-keep').click()
      await expect(page.getByTestId('summary-keep')).toBeDisabled()
      await stage(page, 2)
      await expect(page.getByTestId('summary-checks')).toContainText('숙달 · 목표 달성으로 세지 않아요')
      const events = await page.evaluate(() => (window as unknown as { __vfEvents: { name: string; props: Record<string, unknown> }[] }).__vfEvents)
      expect(events.map(e => e.name)).toContain('csat_summary_explored')
      expect(events.every(e => Object.values(e.props).every(v => typeof v === 'number' || ['stage', 'evidence', 'condition'].includes(String(v))))).toBe(true)
      const actions = await page.evaluate(() => (window as unknown as { __vfActions: unknown[] }).__vfActions)
      expect(actions).toEqual([{ keep: true }])
    })
    test('다음 활동에 바로 접근 가능 · 준비된 과제 이동 · 도크와 강의 이동 보존', async ({ page }) => {
      await page.goto(url('prepared')); await stage(page, 2)
      await expect(page.getByTestId('summary-checks')).toHaveAttribute('data-readiness', 'prepared')
      await controls(page)
      await page.getByTestId('summary-next-checks').click()
      await expect(page.getByTestId('other-scene')).toHaveAttribute('data-scene', 'judgment')
      expect(page.url()).toContain('scene=judgment')
      const dock = page.locator('[data-testid="dock-scene"][data-scene="explain"]')
      await dock.focus(); await page.keyboard.press('Enter')
      await expect(page.getByTestId('learning-summary')).toBeVisible()
      expect(page.url()).toContain('scene=explain')
      await stage(page, 2); await page.getByTestId('summary-next-lecture').click()
      const actions = await page.evaluate(() => (window as unknown as { __vfActions: unknown[] }).__vfActions)
      expect(actions).toEqual([{ go: 'judgment' }, { go: 'explain' }, { lecture: true }])
    })
    test('과제 미준비는 탐색을 막지 않으며 가짜 평가를 만들지 않는다', async ({ page }) => {
      await page.goto(url('preparing')); await stage(page, 1)
      await page.getByTestId('summary-condition-limit').click()
      await stage(page, 2)
      await expect(page.getByTestId('summary-checks-preparing')).toContainText('확인 과제 준비 중')
      await expect(page.getByTestId('summary-next-checks')).toHaveCount(0)
      await expect(page.getByTestId('summary-next-evidence')).toBeVisible()
      await noWriting(page)
      await page.screenshot({ path: `${SHOTS}/preparing-${width}.png`, fullPage: true })
    })
    test('자료 전체 미준비/기록 읽는 중 구별 · 탐색으로 자료를 지어내지 않음', async ({ page }) => {
      await page.goto(url('empty'))
      await expect(page.getByTestId('summary-relation')).toContainText('준비 중')
      await expect(page.getByTestId('summary-evidence-choice')).toHaveCount(0)
      await stage(page, 1)
      await expect(page.getByTestId('summary-principle')).toContainText('준비 중')
      await expect(page.getByTestId('summary-keep')).toHaveCount(0)
      await stage(page, 2)
      await expect(page.getByTestId('summary-next')).toContainText('준비된 활동이 아직 없어요')
      await page.screenshot({ path: `${SHOTS}/empty-${width}.png`, fullPage: true })
      await page.goto(url('loading')); await page.reload()
      await expect(page.getByTestId('summary-history-loading')).toBeVisible()
    })
    test('과거 원본/수정 기록은 읽기 전용 · 근거 짚기 보존', async ({ page }) => {
      await page.goto(url('history'))
      const hist = page.getByTestId('summary-history')
      await hist.locator('summary').click()
      await expect(hist.getByTestId('self-explain-history-item')).toHaveCount(1)
      await expect(hist.getByTestId('note-mine')).toContainText('처음 설명')
      await expect(hist.getByTestId('note-revised')).toContainText('원본은 그대로')
      await expect(hist.getByRole('button', { name: /저장|고쳐|대조/ })).toHaveCount(0)
      await noWriting(page)
      await hist.getByTestId('note-evidence-show').click()
      const actions = await page.evaluate(() => (window as unknown as { __vfActions: unknown[] }).__vfActions)
      expect(actions).toEqual([{ evidence: [2, 3] }])
      expect(await page.getByTestId('pane-explain').evaluate(el => getComputedStyle(el).overflowY)).toBe('auto')
      await page.screenshot({ path: `${SHOTS}/history-${width}.png`, fullPage: true })
    })
  })
}

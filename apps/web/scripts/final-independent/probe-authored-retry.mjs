// apps/web/scripts/final-independent/probe-authored-retry.mjs
// Replay actual isolated-browser retry metadata through captured installed G2 bodies in PGlite.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
const root = path.resolve(import.meta.dirname, '../../../..')
const { PGlite } = createRequire(path.join(root, 'apps/web/package.json'))('@electric-sql/pglite')
const contractPath = path.join(root, 'scripts/research/lm-g1-2-independent/installed-contract.json')
const contract = JSON.parse(fs.readFileSync(contractPath, 'utf8'))
const browser = JSON.parse(fs.readFileSync(path.join(root, 'docs/research/final-independent-20261018/authored-browser/results.json'), 'utf8'))
const db = new PGlite()
const rows = []
try {
  for (const table of ['learning_mutations', 'learning_sessions', 'learning_task_attempts']) {
    const cols = contract.columns.filter(x => x.table_name === table).map(x => x.column_name + ' ' + (x.column_name === 'id' && table === 'learning_task_attempts' ? 'bigint generated by default as identity' : x.data_type) + (x.column_default ? ' default ' + x.column_default : '') + (x.is_nullable === 'NO' ? ' not null' : ''))
    if (table === 'learning_mutations') cols.push('primary key(user_id,client_mutation_id)')
    if (table === 'learning_sessions') cols.push('primary key(id)', 'unique(user_id,client_session_id)')
    if (table === 'learning_task_attempts') cols.push('primary key(id)', 'unique(user_id,client_mutation_id)')
    await db.exec('create table public.' + table + ' (' + cols.join(',') + ')')
  }
  for (const fn of contract.functions) await db.exec(fn.definition)
  for (let i = 0; i < browser.submissions.length; i += 2) {
    const [first, retry] = browser.submissions.slice(i, i + 2)
    assert.equal(first.clientMutationId, retry.clientMutationId)
    assert.notEqual(first.answeredAt, retry.answeredAt)
    const uid = '00000000-0000-4000-8000-000000000001'
    const args = [uid, first.clientMutationId, crypto.randomUUID(), first.clientSessionId, 'theater', 'practice', 'authored:isolated-case', 'independent', first.answeredAt, false, 'authored-central-meaning', null, 'fixture-hash', JSON.stringify(first.response), true, null, null]
    const sql = 'select * from public.learning_attempt_submit(' + args.map((_, j) => '$' + (j + 1)).join(',') + ')'
    const initial = (await db.query(sql, args)).rows[0]
    const exact = (await db.query(sql, args)).rows[0]
    const changed = [...args]; changed[8] = retry.answeredAt
    const actual = (await db.query(sql, changed)).rows[0]
    assert.equal(initial.outcome, 'inserted'); assert.equal(exact.outcome, 'duplicate'); assert.equal(actual.outcome, 'conflict')
    rows.push({ width: [1280, 1440][i / 2], initial: initial.outcome, exactReplay: exact.outcome, browserRetry: actual.outcome, firstAt: first.answeredAt, retryAt: retry.answeredAt })
  }
} finally { await db.close() }
const result = { scope: 'ISOLATED_PGLITE_ONLY; captured installed G2 function bodies, minimal schema, no production triggers/RLS/concurrency claim', ownerCommit: browser.frozenCommit, contractSha256: crypto.createHash('sha256').update(fs.readFileSync(contractPath)).digest('hex'), functions: contract.functions.map(f => ({ name: f.proname, sha256: crypto.createHash('sha256').update(f.definition).digest('hex') })), rows }
fs.writeFileSync(path.join(root, 'docs/research/final-independent-20261018/authored-retry.json'), JSON.stringify(result, null, 2) + '\n')
console.log(JSON.stringify(result, null, 2))

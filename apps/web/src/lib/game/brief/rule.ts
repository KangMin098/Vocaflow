//
//   silent-rule   증거로 규칙을 세워 옳은 칸만 한 번에 제출 → 점수를 걸고 → **철자를 직접 친다**
//                 (group · 3스텝 · 타이핑 · 결정은 제출 뒤 · 게이지 = 막대 + 문 카운터)
//   connections   **어느 규칙을 먼저 칠지**(◆tier × 선점 배수)를 먼저 결정 → 그 규칙의 4칸 확정
//                 (group · 2스텝 · 결정이 먼저 · 비용 타일 · 게이지 = 막대 + 기회 핍)
//   lexicon-hands 주문 칸에 카드를 **순서대로 올린 뒤**(assemble 슬롯 2) 그 묶음을 낼지 되무를지
//                 (assemble · 2스텝 · 결정이 나중 · 슬롯 · 게이지 = 납기 + 목표 + 검수 핍)
//   word-customs  ×2 서약 여부 → 승인/거부 → **거부라면 어느 축이 위조인지 이름을 댄다**
//                 (judge · 3스텝 · 서약은 도착 3초 창 · 게이지 = 하루 시계 + 오심 여유 핍)
//
// 수치 원칙(v08.5): **확인 못 한 숫자는 적지 않는다.** 상수 하나만 읽고 곱해지는 계수를
// 빠뜨리거나(누진 비용 · 상한 · 편성별 곡선), 화면에 없는 라벨을 지어내면 튜토리얼이 아니라
// 오답 안내가 된다. 아래 모든 수치는 각 게임 소스에서 직접 읽었고, 조건부로 달라지는 값은

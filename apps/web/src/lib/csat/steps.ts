export const readySteps = (): CsatStep[] => CSAT_STEPS.filter((s) => s.state === 'ready')

/**
 * 이 경로가 어느 단계인가. 못 찾으면 `null`.
 *
 * ⚠️ **하위 경로도 그 단계로 센다** — `/csat/map/…` 로 들어가도 인디케이터가 꺼지지 않는다.
 *
 * ⚠️ **`/csat` 는 정확히 일치할 때만 ① 이다.** 접두사로 세면 `/csat/map` 도 ① 에 걸려
 *   두 칸이 동시에 켜진다. 가장 긴 `href` 가 이기게 두면 대부분 해결되지만, 그것에
 *   기대지 않고 뿌리는 못박는다 — 나중에 `/csat/x` 가 늘 때 조용히 깨진다.
 */
export function stepFor(pathname: string): CsatStep | null {
  const hit = CSAT_STEPS.filter((s) => {
    if (!s.href) return false
    if (s.href === '/csat') return pathname === '/csat'
    return pathname === s.href || pathname.startsWith(`${s.href}/`)
  })
  // 가장 긴 `href` 가 가장 구체적이다.
  return hit.sort((a, b) => (b.href?.length ?? 0) - (a.href?.length ?? 0))[0] ?? null
}

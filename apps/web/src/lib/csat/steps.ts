/** 그 단계를 지금 쓸 수 있는가. */
export type StepState =
  /** 화면이 있고 들어갈 수 있다. */
  | 'ready'
  /** 아직 못 짓는다 — 링크를 걸지 않는다. */
  | 'later'

export interface CsatStep {
  /** 1부터. 레일에 찍히는 번호다. */
  no: number
  /** 화면 이름 — 짧게. */
  label: string
  /**
   * **학습자가 여기서 하는 동사.** 이것이 없으면 그 화면은 화면이 아니라 문서다.
   * (`CSAT_LEARNER_DELIVERY.md` §4 구성 규칙 — 화면마다 답하는 질문 하나.)
   */
  verb: string
  /** 라벨이 말하지 않는 것 — 이 화면이 답하는 질문. */
  says: string
  href: string | null
  state: StepState
}

